export const MESSAGES = { en, zh, de, fr, pl, uk, vi, pt, tr };

/** Map a stored interface language (``en``, ``zh``, ``zh-CN`` …) to shell copy. */
export function resolveLanguage(value) {
  const code = String(value ?? '').toLowerCase().split(/[-_]/)[0];
  return Object.hasOwn(MESSAGES, code) ? code : 'en';
}

export function translate(language, key, values = {}) {
  const text = MESSAGES[resolveLanguage(language)][key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in values ? String(values[name]) : match));
}
